#!/usr/bin/env bash
# Starts the local GitLab stand and bootstraps it. Idempotent: safe to re-run.
#
#   e2e/local/up.sh
#
# Environment (all optional):
#   GITLAB_VERSION   gitlab/gitlab-ce tag (default in docker-compose.yml); use the prod version
#   GITLAB_IMAGE     full image reference instead (another edition, a mirror)
#   RUNNER_VERSION   gitlab/gitlab-runner tag (default latest)
#   UP_TIMEOUT       seconds to wait for GitLab to become healthy (default 1500)
#   RUNNER_NETWORKING  network (default): job containers join the "reviewbot-local"
#                      network and reach http://gitlab:8929 directly;
#                    per-build: a network per job (CI services always work), GitLab
#                      reached through host-gateway:8929. Switch if CI services
#                      (postgres in rb-php) are not resolvable in jobs.
#   SKIP_RUNNER=1    do not register a runner
#   NEW_TOKENS=1     re-create all tokens even if .env.local still works
#
# Writes e2e/local/.env.local (chmod 600, git-ignored) with the URL, tokens and
# root password. Prints only variable names, never values.
set -euo pipefail
# shellcheck source=lib.sh
. "$(dirname "$0")/lib.sh"

need docker curl jq openssl awk
docker compose version >/dev/null 2>&1 || die "docker compose v2 is required"

UP_TIMEOUT=${UP_TIMEOUT:-1500}
RUNNER_NETWORKING=${RUNNER_NETWORKING:-network}
mkdir -p "$STATE_DIR"
chmod 700 "$STATE_DIR"

step "Starting GitLab and GitLab Runner (first start takes 5-10 minutes)"
compose up -d

cid=$(compose ps -q gitlab)
[ -n "$cid" ] || die "gitlab container is not running (docker compose logs gitlab)"

step "Waiting for GitLab to become healthy (timeout ${UP_TIMEOUT}s)"
start=$(date +%s)
last=0
while :; do
  status=$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$cid" 2>/dev/null || echo unknown)
  if [ "$status" = healthy ]; then
    code=$(curl -s -o /dev/null -w '%{http_code}' "$GITLAB_HOST_URL/users/sign_in" || true)
    [ "$code" = 200 ] && break
  fi
  now=$(date +%s)
  elapsed=$((now - start))
  [ "$elapsed" -lt "$UP_TIMEOUT" ] || die "GitLab is not healthy after ${UP_TIMEOUT}s (status: $status). See: docker compose -f $COMPOSE_FILE logs --tail 200 gitlab"
  if [ $((elapsed - last)) -ge 30 ]; then
    log "  ... ${elapsed}s, container status: $status"
    last=$elapsed
  fi
  [ "$status" = exited ] && die "gitlab container exited (docker compose -f $COMPOSE_FILE logs gitlab)"
  sleep 5
done
log "GitLab is up at $GITLAB_HOST_URL (as http://gitlab:8929 for the bot and CI)"

# Re-use the tokens from .env.local while they work.
mode=tokens
if [ -z "${NEW_TOKENS:-}" ] && [ -f "$ENV_FILE" ]; then
  # shellcheck disable=SC1090
  (set -a; . "$ENV_FILE"; set +a
   api "$GITLAB_SERVICE_TOKEN" GET /user
   api_ok && [ "$(printf '%s' "$API_BODY" | jq -r .is_admin)" = true ]) && mode=ensure
fi

step "Bootstrapping users, groups and tokens (gitlab-rails runner, mode: $mode; ~1 minute)"
out=$(compose exec -T -e RB_MODE="$mode" gitlab \
  gitlab-rails runner /opt/reviewbot-local/bootstrap.rb 2>"$STATE_DIR/bootstrap.log") || {
  log "bootstrap failed, last lines of $STATE_DIR/bootstrap.log:"
  tail -n 30 "$STATE_DIR/bootstrap.log" >&2
  die "bootstrap failed"
}
grep '^bootstrap:' "$STATE_DIR/bootstrap.log" >&2 || true

val() { printf '%s\n' "$out" | awk -v k="RBOUT $1=" 'index($0, k) == 1 { print substr($0, length(k) + 1) }' | tail -n 1; }
running=$(val GITLAB_VERSION_RUNNING)

if [ "$mode" = tokens ]; then
  root_pw=$(val GITLAB_ROOT_PASSWORD)
  svc=$(val GITLAB_SERVICE_TOKEN)
  bot=$(val GITLAB_TOKEN)
  dev=$(val RB_DEV_TOKEN)
  guest=$(val RB_GUEST_TOKEN)
  for v in root_pw svc bot dev guest; do
    [ -n "${!v}" ] || die "bootstrap did not return all secrets (see $STATE_DIR/bootstrap.log)"
  done
  secret=$(openssl rand -hex 32)
  old_umask=$(umask)
  umask 077
  tmp=$(mktemp "$LOCAL_DIR/.env.local.XXXXXX")
  {
    echo "# Generated by e2e/local/up.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Local test stand only."
    echo "# Never commit, never paste into chat. Re-create: NEW_TOKENS=1 e2e/local/up.sh"
    echo "GITLAB_URL=http://gitlab:8929"
    echo "GITLAB_HOST_URL=$GITLAB_HOST_URL"
    echo "GITLAB_TOKEN=$bot"
    echo "GITLAB_SERVICE_TOKEN=$svc"
    echo "RB_DEV_TOKEN=$dev"
    echo "RB_GUEST_TOKEN=$guest"
    echo "GITLAB_WEBHOOK_SECRET=$secret"
    echo "GITLAB_ROOT_USER=root"
    echo "GITLAB_ROOT_PASSWORD=$root_pw"
  } >"$tmp"
  chmod 600 "$tmp"
  mv "$tmp" "$ENV_FILE"
  umask "$old_umask"
  unset root_pw svc bot dev guest secret
  log "wrote $ENV_FILE (chmod 600)"
else
  log "tokens in $ENV_FILE still work, kept (NEW_TOKENS=1 to re-create)"
fi
unset out

load_env

step "Instance settings"
api_json "$GITLAB_SERVICE_TOKEN" PUT /application/settings '{
  "signup_enabled": false,
  "allow_local_requests_from_web_hooks_and_services": true,
  "auto_devops_enabled": false,
  "deletion_adjourned_period": 1
}'
api_ok || die "PUT /application/settings: HTTP $API_STATUS $(api_message)"
log "signup off, local webhook targets allowed, Auto DevOps off"

if [ -z "${SKIP_RUNNER:-}" ]; then
  step "GitLab Runner (docker executor, networking: $RUNNER_NETWORKING)"
  if compose exec -T gitlab-runner gitlab-runner list 2>&1 | grep -q 'reviewbot-local'; then
    log "runner reviewbot-local is already registered"
  else
    api "$GITLAB_SERVICE_TOKEN" POST /user/runners \
      --data-urlencode runner_type=instance_type \
      --data-urlencode description=reviewbot-local \
      --data-urlencode run_untagged=true
    api_ok || die "POST /user/runners: HTTP $API_STATUS $(api_message)"
    CI_SERVER_TOKEN=$(printf '%s' "$API_BODY" | jq -r .token)
    [ -n "$CI_SERVER_TOKEN" ] && [ "$CI_SERVER_TOKEN" != null ] || die "POST /user/runners returned no token"
    export CI_SERVER_TOKEN
    set -- --non-interactive --name reviewbot-local --url http://gitlab:8929 \
      --clone-url http://gitlab:8929 --executor docker --docker-image alpine:3.20 \
      --docker-pull-policy if-not-present
    case $RUNNER_NETWORKING in
      network) set -- "$@" --docker-network-mode reviewbot-local ;;
      per-build) set -- "$@" --env FF_NETWORK_PER_BUILD=true --docker-extra-hosts gitlab:host-gateway ;;
      *) die "RUNNER_NETWORKING must be network or per-build" ;;
    esac
    # The runner token goes through the environment (CI_SERVER_TOKEN), not argv.
    compose exec -T -e CI_SERVER_TOKEN gitlab-runner gitlab-runner register "$@" >/dev/null 2>"$STATE_DIR/runner.log" || {
      tail -n 20 "$STATE_DIR/runner.log" >&2
      die "gitlab-runner register failed"
    }
    unset CI_SERVER_TOKEN
    compose exec -T gitlab-runner sed -i "s/^concurrent = .*/concurrent = ${RUNNER_CONCURRENCY:-8}/" /etc/gitlab-runner/config.toml
    log "runner reviewbot-local registered (instance runner, untagged jobs, concurrent = ${RUNNER_CONCURRENCY:-8})"
  fi
fi

step "Done"
cat >&2 <<EOF
GitLab:       $GITLAB_HOST_URL  (http://gitlab:8929 with "127.0.0.1 gitlab" in /etc/hosts)
Log in:       root / GITLAB_ROOT_PASSWORD from e2e/local/.env.local
Secrets file: e2e/local/.env.local  (GITLAB_URL GITLAB_HOST_URL GITLAB_TOKEN GITLAB_SERVICE_TOKEN
              RB_DEV_TOKEN RB_GUEST_TOKEN GITLAB_WEBHOOK_SECRET GITLAB_ROOT_PASSWORD)
Running:      GitLab ${running:-?}
Next:         e2e/local/seed.sh
EOF
